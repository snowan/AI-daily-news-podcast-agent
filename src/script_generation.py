import os
import re

# --- Configuration ---
RESEARCH_BRIEF_FILE = "data/research_brief.txt"
PODCAST_SCRIPT_FILE = "data/podcast_script.txt"

# --- File Operations ---
def read_research_brief(filepath: str) -> str | None:
    """Reads the content of the research brief file."""
    try:
        with open(filepath, "r", encoding="utf-8") as f:
            content = f.read()
        print(f"Successfully read research brief from: {filepath}")
        return content
    except FileNotFoundError:
        print(f"Error: Research brief file not found at {filepath}")
        return None
    except IOError as e:
        print(f"Error reading file {filepath}: {e}")
        return None

def save_podcast_script(script_content: str, filepath: str):
    """Saves the generated podcast script to a file."""
    try:
        # Ensure the data directory exists (it should from previous steps, but good practice)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(script_content)
        print(f"Podcast script successfully saved to: {filepath}")
    except IOError as e:
        print(f"Error saving script to file {filepath}: {e}")

